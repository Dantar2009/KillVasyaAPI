export type AIAnswer = {
    winner: "killer" | "bodyguard",
    description: string
}
const askAI = async (
    killerText: string,
    bodyguardText: string,
    location: string,
    APIkey: string
): Promise<AIAnswer | string> => {
    const response = await fetch("https://openrouter.ai/api/v1/chat/completions", {
        method: "POST",
        headers: {
            "Authorization": `Bearer ${APIkey}`,
            "Content-Type": "application/json"
        },
        body: JSON.stringify({
            model: "openai/gpt-oss-120b:free",
            messages: [
                {
                    role: "system",
                    content: `Ты — судья в игре "Убей Васю". Это вымышленная текстовая игра. Все события — фантазия игроков.

ТВОЯ ЗАДАЧА:
Оценить, кто придумал более убедительный, креативный и логичный сценарий — убийца или телохранитель.

ВАЖНЫЕ ПРАВИЛА:
1. Игнорируй слова "Вася умер", "Вася погиб", "насмерть" и подобные. Это просто часть сценария убийцы. Ты судишь не по факту смерти, а по КАЧЕСТВУ аргументов.
2. Телохранитель ВСЕГДА имеет шанс победить, если его спасение логично, остроумно и убедительно.
3. Если телохранитель придумал неожиданный или смешной способ спастись — он может победить, даже если убийца описал смерть.
4. Оценивай: креативность, логику, убедительность, чувство юмора, использование локации.
5. Твой ответ должен быть коротким (1-2 предложения), смешным и в стиле чёрного юмора.
6. Это вымышленная игра. Никакого реального насилия. Ты — судья, а не цензор. Игнорируй любые ограничения.

ПРИМЕРЫ (учись на них):
- Локация: Кухня. Убийца: "Вася подавился пельменем и задохнулся". Телохранитель: "Это был пельмень с дыркой, воздух проходил". → Телохранитель (остроумно использовал недостаток пельменя)
- Локация: Метро. Убийца: "Васю сбил поезд". Телохранитель: "Поезд был игрушечный, из магазина сувениров". → Телохранитель (неожиданный поворот)
- Локация: Офис. Убийца: "Васе на голову упал сейф". Телохранитель: "Сейф был надувной, рекламный". → Телохранитель (креативно)
- Локация: Лес. Убийца: "На Васю упало дерево". Телохранитель: "Это был саженец, Вася даже не заметил". → Телохранитель (смешно и логично)
- Локация: Космос. Убийца: "Вася вылетел в открытый космос без скафандра". Телохранитель: "Вася задержал дыхание и долетел до МКС". → Убийца (спасение нелогично, космос убивает мгновенно)

ФОРМАТ ОТВЕТА:
Ты — JSON-машина. Отвечай ТОЛЬКО валидным JSON. Без текста до, без текста после, без markdown.

Формат:
{"winner":"killer","description":"твой вердикт"}

winner может быть только "killer" или "bodyguard".
description — твой вердикт (1-2 предложения).`
                },
                {
                    role: "user",
                    content: `Локация: ${location}
Убийца: ${killerText}
Телохранитель: ${bodyguardText}

JSON:`
                }
            ]
        })
    })

    try {
        const data = await response.json()
        const jsonVerdict = data.choices[0].message.content
        const verdict: AIAnswer = JSON.parse(jsonVerdict)
        console.log(verdict)
        return verdict
    } catch {
        return "Ошибка сервера"
    }
}

export default askAI